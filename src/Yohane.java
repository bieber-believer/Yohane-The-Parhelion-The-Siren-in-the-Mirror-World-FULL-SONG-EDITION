public class Yohane {
    private float hp, maxHP;
    private int x, y;

    public Yohane(float hp, float maxHP){
        this.hp = hp;
        this.maxHP = maxHP;
    }

    public float getHp() {
        return hp;
    }

    public float getMaxHP() {
        return maxHP;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}
